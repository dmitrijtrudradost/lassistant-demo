    pdf.body(
        "Целостность — это когда для программы метка одна непрерывная строка "
        "от [ до ]. Программа ищет, например, [contract_reference] "
        "и заменяет её целиком на значение из формы "
        "(например, 90-П от «1» ноября 2023 г.)."
    )

