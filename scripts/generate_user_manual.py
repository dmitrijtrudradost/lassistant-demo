    pdf.body(
        "В Word вы видите одну фразу: [contract_reference]. "
        "Даже если Word внутри файла разбил её на части, движок программы "
        "часто это исправляет. Надёжнее всего — скопировать плейсхолдер "
        "целиком из списка полей или из рабочего шаблона и не редактировать "
        "его по символам."
    )

    pdf.h2("Когда целостность нарушена (плохо)")
    pdf.body(
        "Вы вручную меняете плейсхолдер по частям. Word запоминает это "
        "как несколько фрагментов:"
    )
