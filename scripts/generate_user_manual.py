#!/usr/bin/env python3
"""Генерирует PDF-руководство пользователя «Помощник юриста»."""

import shutil
from pathlib import Path
from fpdf import FPDF
from fpdf.enums import XPos, YPos

FONTS    = Path("C:/Windows/Fonts")
GRAY     = (100, 100, 100)
BLACK    = (30,  30,  30)
BLUE     = (0,   70,  160)
LIGHT    = (240, 245, 250)
LM       = 20   # левый отступ
RM       = 20   # правый отступ
PW       = 210 - LM - RM   # ширина текстовой области


class Manual(FPDF):
    def __init__(self):
        super().__init__()
        self.set_margins(LM, 18, RM)
        self.add_font("Ar",  style="",  fname=str(FONTS / "arial.ttf"))
        self.add_font("Ar",  style="B", fname=str(FONTS / "arialbd.ttf"))
        self.add_font("Ar",  style="I", fname=str(FONTS / "ariali.ttf"))
        self.set_auto_page_break(True, margin=20)

    def header(self):
        self.set_font("Ar", "B", 9)
        self.set_text_color(*GRAY)
        self.cell(0, 8, "Lassistant — Руководство пользователя",
                  new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_draw_color(*GRAY)
        self.line(LM, self.get_y(), self.w - RM, self.get_y())
        self.ln(4)

    def footer(self):
        self.set_y(-15)
        self.set_font("Ar", "I", 8)
        self.set_text_color(*GRAY)
        self.cell(0, 10, f"Стр. {self.page_no()}", align="C")

    # ── вспомогательные ────────────────────────────────────────────────────
    def h1(self, text: str):
        self.ln(4)
        self.set_font("Ar", "B", 15)
        self.set_text_color(*BLUE)
        self.set_x(LM)
        self.cell(0, 10, text, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_draw_color(*BLUE)
        self.line(LM, self.get_y(), self.w - RM, self.get_y())
        self.ln(4)

    def h2(self, text: str):
        self.ln(3)
        self.set_font("Ar", "B", 12)
        self.set_text_color(*BLACK)
        self.set_x(LM)
        self.cell(0, 8, text, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(1)

    def body(self, text: str):
        self.set_font("Ar", "", 11)
        self.set_text_color(*BLACK)
        self.set_x(LM)
        self.multi_cell(PW, 6, text)
        self.ln(1)

    def note(self, text: str):
        self.set_fill_color(*LIGHT)
        self.set_font("Ar", "I", 10)
        self.set_text_color(*GRAY)
        self.set_x(LM)
        self.multi_cell(PW, 6, "  " + text, fill=True)
        self.ln(2)

    def step(self, num: int, text: str):
        self.set_font("Ar", "B", 11)
        self.set_text_color(*BLUE)
        self.set_x(LM)
        num_w = 8
        self.cell(num_w, 6, f"{num}.", new_x=XPos.RIGHT, new_y=YPos.TOP)
        self.set_font("Ar", "", 11)
        self.set_text_color(*BLACK)
        self.multi_cell(PW - num_w, 6, text)
        self.ln(1)

    def bullet(self, text: str):
        self.set_font("Ar", "", 11)
        self.set_text_color(*BLACK)
        self.set_x(LM + 4)
        bul_w = 5
        self.cell(bul_w, 6, "•", new_x=XPos.RIGHT, new_y=YPos.TOP)
        self.multi_cell(PW - 4 - bul_w, 6, text)


